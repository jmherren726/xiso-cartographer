"""Embeds the pinned CA bundle in the build as C data (ADR 0012 §3).

    python -I tools/cacert/embed_cacert.py --in third_party/cacert/cacert.pem --out cacert_data.c

The bundle's SHA-256 must match the pin next to it (cacert.pem.sha256), so the bundle can only
change in a PR that also changes the pin. The output defines what core/src/cacert.h declares:
the PEM text as bytes (decoded at startup by xc_tls_anchors_parse, the same loader as the
E:\\Apps\\xcat\\cacert.pem override) and the date of Mozilla's data, for logs.
"""

from __future__ import annotations

import argparse
import hashlib
import re
import sys


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--in", dest="src", required=True, help="the PEM bundle")
    ap.add_argument("--out", required=True, help="the C file to write")
    args = ap.parse_args(argv)

    with open(args.src, "rb") as f:
        data = f.read()
    with open(args.src + ".sha256", encoding="ascii") as f:
        pin = f.read().split()[0].lower()
    digest = hashlib.sha256(data).hexdigest()
    if digest != pin:
        print(f"embed_cacert: {args.src} has SHA-256 {digest}, but the pin says {pin}", file=sys.stderr)
        return 1
    m = re.search(rb"Certificate data from Mozilla as of: ([^\r\n]+)", data)
    date = m.group(1).decode("ascii") if m else "unknown"
    if not re.fullmatch(r"[ -~]+", date) or '"' in date or "\\" in date:
        print(f"embed_cacert: unexpected date line {date!r}", file=sys.stderr)
        return 1

    lines = [
        "/* Generated by tools/cacert/embed_cacert.py from third_party/cacert/cacert.pem. */",
        f"/* SHA-256 {digest}; Mozilla data as of {date}. Do not edit. */",
        '#include "cacert.h"',
        "",
        "const unsigned char xc_cacert_pem[] = {",
    ]
    for i in range(0, len(data), 16):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i : i + 16]) + ",")
    lines += [
        "};",
        "const size_t xc_cacert_pem_len = sizeof xc_cacert_pem;",
        f'const char xc_cacert_date[] = "{date}";',
        "",
    ]
    with open(args.out, "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(lines))
    return 0


if __name__ == "__main__":
    sys.exit(main())
